-- =========================================================
--  TABLA: asistencia_asamblea (mejorada)
-- =========================================================
CREATE TABLE asistencia_asamblea (
  id_tenant                 BIGINT NOT NULL,
  id_asistencia             BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  id_asamblea               BIGINT NOT NULL,
  id_persona                BIGINT NOT NULL,
  estado                    VARCHAR(15) NOT NULL DEFAULT 'PENDIENTE',
  hora_llegada              TIME,
  es_padronado_en_momento   BOOLEAN NOT NULL,
  tiene_derecho_voto        BOOLEAN NOT NULL DEFAULT FALSE,
  voto_emitido              BOOLEAN NOT NULL DEFAULT FALSE,
  observaciones             TEXT,

  created_at                TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_by_user           BIGINT NOT NULL,
  updated_at                TIMESTAMPTZ NULL,
  updated_by_user           BIGINT NULL,

  anulado                   BOOLEAN NOT NULL DEFAULT FALSE,
  anulado_at                TIMESTAMPTZ NULL,
  anulado_by_user           BIGINT NULL,
  motivo_anulacion          TEXT NULL,

  CONSTRAINT pk_asistencia_asamblea PRIMARY KEY (id_tenant, id_asistencia),
  CONSTRAINT fk_aa_tenant FOREIGN KEY (id_tenant) REFERENCES tenants(id_tenant),
  CONSTRAINT fk_aa_asamblea FOREIGN KEY (id_tenant, id_asamblea)
    REFERENCES asambleas (id_tenant, id_asamblea),
  CONSTRAINT fk_aa_persona FOREIGN KEY (id_tenant, id_persona)
    REFERENCES personas (id_tenant, id_persona),
  CONSTRAINT ux_asistencia_asamblea UNIQUE (id_tenant, id_asamblea, id_persona),
  CONSTRAINT ck_asistencia_estado CHECK (
    estado IN ('PENDIENTE','ASISTIO','TARDE','FALTO','JUSTIFICADO')
  ),
  CONSTRAINT ck_asistencia_anulado CHECK (
    (anulado = FALSE AND anulado_at IS NULL AND anulado_by_user IS NULL)
    OR
    (anulado = TRUE AND anulado_at IS NOT NULL AND anulado_by_user IS NOT NULL)
  ),
  CONSTRAINT fk_aa_created_by FOREIGN KEY (created_by_user) REFERENCES auth_users(id_user),
  CONSTRAINT fk_aa_updated_by FOREIGN KEY (updated_by_user) REFERENCES auth_users(id_user),
