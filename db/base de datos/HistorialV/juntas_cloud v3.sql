-- =========================================================
-- JUNTASCLOUD V3
-- PostgreSQL - multi-tenant SaaS
-- Base: una sola BD, múltiples asociaciones
-- =========================================================

CREATE EXTENSION IF NOT EXISTS citext;

-- =========================================================
-- HELPERS
-- =========================================================
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS trigger AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- =========================================================
-- 0) MODULOS GLOBALES (mODULOS PERFILES)
-- =========================================================
CREATE TABLE app_modules (
  module_code VARCHAR(80) PRIMARY KEY,
  nombre VARCHAR(100) NOT NULL,
  grupo VARCHAR(100) NOT NULL,
  orden INT NOT NULL DEFAULT 0,
  activo BOOLEAN NOT NULL DEFAULT TRUE
);

-- =========================================================
-- 0) USERS GLOBALES (LOGIN)
-- =========================================================
CREATE TABLE auth_users (
  id_user              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  email                CITEXT NOT NULL,
  nombres              VARCHAR(100) NOT NULL,
  apellidos            VARCHAR(100) NOT NULL,
  password_hash        VARCHAR(255) NOT NULL,
  estado               VARCHAR(15) NOT NULL DEFAULT 'ACTIVO',
  email_verified       BOOLEAN NOT NULL DEFAULT FALSE,
  email_verified_at    TIMESTAMPTZ NULL,
  last_login_at        TIMESTAMPTZ NULL,
  created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at           TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT pk_auth_users PRIMARY KEY (id_user),
  CONSTRAINT ux_auth_users_email UNIQUE (email),
  CONSTRAINT ck_auth_users_estado CHECK (estado IN ('ACTIVO','INACTIVO','BLOQUEADO'))
);
CREATE INDEX inx_auth_users_estado ON auth_users (estado);

CREATE TRIGGER trg_auth_users_updated_at
BEFORE UPDATE ON auth_users
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();


CREATE TABLE auth_user_tokens (
  id_token             BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  id_user              BIGINT NOT NULL,
  token_hash           VARCHAR(255) NOT NULL,
  token_type           VARCHAR(30) NOT NULL,
  expires_at           TIMESTAMPTZ NOT NULL,
  used_at              TIMESTAMPTZ NULL,
  revoked_at           TIMESTAMPTZ NULL,
  created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
  created_ip           VARCHAR(45),
  user_agent           TEXT,

  CONSTRAINT pk_auth_user_tokens PRIMARY KEY (id_token),
  CONSTRAINT fk_auth_user_tokens_user FOREIGN KEY (id_user)
    REFERENCES auth_users(id_user),
  CONSTRAINT ux_auth_user_tokens_hash UNIQUE (token_hash),
  CONSTRAINT ck_auth_user_tokens_type CHECK (
    token_type IN ('VERIFY_EMAIL','RESET_PASSWORD','CHANGE_EMAIL')
  ),
  CONSTRAINT ck_auth_user_tokens_dates CHECK (expires_at > created_at)
);
CREATE INDEX inx_auth_user_tokens_user ON auth_user_tokens (id_user);
CREATE INDEX inx_auth_user_tokens_user_type ON auth_user_tokens (id_user, token_type);
CREATE INDEX inx_auth_user_tokens_expires ON auth_user_tokens (expires_at);



CREATE TABLE auth_login_logs (
  id_log               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_user              BIGINT NULL, -- null si fue intento fallido con email inexistente
  email                CITEXT NOT NULL,
  login_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
  success              BOOLEAN NOT NULL,
  ip_address           VARCHAR(45),
  user_agent           TEXT,
  failure_reason       VARCHAR(100),

  CONSTRAINT fk_login_user FOREIGN KEY (id_user)
    REFERENCES auth_users(id_user)
);
CREATE INDEX inx_login_logs_user ON auth_login_logs (id_user);
CREATE INDEX inx_login_logs_date ON auth_login_logs (login_at);
CREATE INDEX inx_login_logs_success ON auth_login_logs (success);


-- =========================================================
-- 1) TENANTS
-- =========================================================
CREATE TABLE tenants (
  id_tenant            BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  nombre               VARCHAR(150) NOT NULL,
  tipo_documento       VARCHAR(15) NULL,
  numero_documento     VARCHAR(20) NULL,
  estado               VARCHAR(15) NOT NULL DEFAULT 'ACTIVO',
  observaciones        VARCHAR(300),
  owner_user_id        BIGINT NOT NULL,
  created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at           TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT pk_tenants PRIMARY KEY (id_tenant),
  CONSTRAINT fk_tenants_owner FOREIGN KEY (owner_user_id) REFERENCES auth_users(id_user),
  CONSTRAINT ux_tenants_nombre UNIQUE (owner_user_id, nombre),
  CONSTRAINT ck_tenants_estado CHECK (estado IN ('ACTIVO','INACTIVO','SUSPENDIDO')),
  CONSTRAINT ck_tenants_tipo_documento CHECK (
    tipo_documento IS NULL OR tipo_documento IN ('RUC','DNI','OTRO')
  )
);
CREATE INDEX inx_tenants_estado ON tenants (estado);

CREATE TRIGGER trg_tenants_updated_at
BEFORE UPDATE ON tenants
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();

