-- =========================================================
-- 2) MEMBRESÍAS tenant_users
-- =========================================================
CREATE TABLE tenant_users (
  id_tenant            BIGINT NOT NULL,
  id_user              BIGINT NOT NULL,
  role                 VARCHAR(15) NOT NULL DEFAULT 'MEMBER',
  estado               VARCHAR(15) NOT NULL DEFAULT 'PENDIENTE',
  joined_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
  accepted_at          TIMESTAMPTZ NULL,
  ended_at             TIMESTAMPTZ NULL,
  invited_by           BIGINT NULL,
  id_persona           BIGINT NULL,-- opcional: vincular a una persona del padrón de ESA junta
  id_profile           BIGINT NULL, -- PERFIL

  CONSTRAINT pk_tenant_users PRIMARY KEY (id_tenant, id_user),
  CONSTRAINT fk_tu_tenant FOREIGN KEY (id_tenant) REFERENCES tenants(id_tenant),
  CONSTRAINT fk_tu_user FOREIGN KEY (id_user) REFERENCES auth_users(id_user),
  CONSTRAINT fk_tu_invited FOREIGN KEY (invited_by) REFERENCES auth_users(id_user),
  -- CONSTRAINT fk_tenant_users_profile FOREIGN KEY (id_tenant, id_profile) REFERENCES tenant_profiles(id_tenant, id_profile),

  CONSTRAINT ck_tu_role CHECK (role IN ('OWNER','ADMIN','MEMBER')),
  CONSTRAINT ck_tu_estado CHECK (estado IN ('PENDIENTE','ACTIVO','INACTIVO','RECHAZADO')),
  CONSTRAINT ck_tu_ended CHECK (ended_at IS NULL OR ended_at >= joined_at)
);

CREATE INDEX inx_tenant_users_user ON tenant_users (id_user);
CREATE INDEX inx_tenant_users_tenant_role_estado ON tenant_users (id_tenant, role, estado);

CREATE UNIQUE INDEX ux_one_owner_per_tenant
ON tenant_users (id_tenant)
WHERE role = 'OWNER' AND estado = 'ACTIVO';


-- =========================================================
-- 3) INVITACIONES (recomendado para "compartir")
-- =========================================================

CREATE TABLE tenant_invitations (
  id_invitation        BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  id_tenant            BIGINT NOT NULL,-- A qué junta pertenece la invitación.
  email                CITEXT NOT NULL,--A qué correo se está invitando.(No necesitas que el usuario exista aún.)
  role                 VARCHAR(15) NOT NULL DEFAULT 'MEMBER',--Qué rol tendrá si acepta.
  token_hash           VARCHAR(255) NOT NULL,--Token único para aceptar la invitación.
  status               VARCHAR(15) NOT NULL DEFAULT 'PENDING',--Estado actual de la invitación.
  expires_at           TIMESTAMPTZ NOT NULL,--Fecha límite para aceptar.
  accepted_at          TIMESTAMPTZ NULL,--Cuándo se aceptó la invitación.
  revoked_at           TIMESTAMPTZ NULL,--Cuándo se rechazo la invitación.
  invited_by           BIGINT NOT NULL,--Qué usuario hizo la invitación.
  created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),--Cuándo se creó la invitación.

  CONSTRAINT pk_tenant_invitations PRIMARY KEY (id_invitation),
  CONSTRAINT fk_inv_tenant FOREIGN KEY (id_tenant) REFERENCES tenants(id_tenant),
  CONSTRAINT fk_inv_user FOREIGN KEY (invited_by) REFERENCES auth_users(id_user),

  CONSTRAINT ux_inv_token_hash UNIQUE (token_hash),
  CONSTRAINT ck_inv_role CHECK (role IN ('ADMIN','MEMBER')),
  CONSTRAINT ck_inv_status CHECK (status IN ('PENDING','ACCEPTED','REVOKED','EXPIRED')),
  CONSTRAINT ck_inv_dates CHECK (expires_at > created_at)
);

CREATE INDEX inx_inv_tenant ON tenant_invitations (id_tenant);
CREATE INDEX inx_inv_email ON tenant_invitations (email);
CREATE INDEX inx_inv_status ON tenant_invitations (status);

CREATE UNIQUE INDEX ux_inv_pending_per_email
ON tenant_invitations (id_tenant, email)
WHERE status = 'PENDING';





-- =========================================================
-- 4) PERSONAS
-- =========================================================
CREATE TABLE personas (
  id_tenant            BIGINT NOT NULL,
  id_persona           BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,

  nombres              VARCHAR(100) NOT NULL,
  apellido_paterno     VARCHAR(100) NOT NULL,
  apellido_materno     VARCHAR(100) NOT NULL,
  dni                  VARCHAR(15),
  email                CITEXT NULL,
  telefono             VARCHAR(20),
  direccion            VARCHAR(200),
  referencia_vivienda  VARCHAR(200),

  tipo_participante    VARCHAR(20) NOT NULL DEFAULT 'NO_PADRONADO',
  estado               VARCHAR(20) NOT NULL DEFAULT 'ACTIVO',

  fecha_registro       DATE NOT NULL DEFAULT CURRENT_DATE,
  fecha_baja           DATE NULL,
  observaciones        TEXT,

  created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at           TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT pk_personas PRIMARY KEY (id_tenant, id_persona),
  CONSTRAINT fk_personas_tenant FOREIGN KEY (id_tenant) REFERENCES tenants(id_tenant),

  CONSTRAINT ck_personas_tipo CHECK (tipo_participante IN ('PADRONADO','NO_PADRONADO','INVITADO')),
  CONSTRAINT ck_personas_estado CHECK (estado IN ('ACTIVO','SUSPENDIDO','RETIRADO','FALLECIDO')),
  CONSTRAINT ck_personas_baja CHECK (fecha_baja IS NULL OR fecha_baja >= fecha_registro)
);

CREATE INDEX inx_personas_tenant ON personas (id_tenant);
CREATE INDEX inx_personas_nombre ON personas (id_tenant, apellido_paterno, apellido_materno, nombres);

CREATE UNIQUE INDEX ux_personas_dni
    ON personas (id_tenant, dni)
    WHERE dni IS NOT NULL;

CREATE UNIQUE INDEX ux_tenant_users_persona
ON tenant_users (id_tenant, id_persona)
WHERE id_persona IS NOT NULL;


CREATE TRIGGER trg_personas_updated_at
BEFORE UPDATE ON personas
FOR EACH ROW
EXECUTE FUNCTION set_updated_at();


