-- =============================================================================
-- 7. MEMBRESÍAS DEL TENANT
-- =============================================================================
--
-- Aquí solo existen usuarios que ya pertenecen al tenant.
-- Las invitaciones pendientes se almacenan exclusivamente en
-- tenant_invitations para evitar duplicidad y desincronización de estados.

CREATE TABLE public.tenant_users (
  id_tenant            BIGINT      NOT NULL,
  id_user              BIGINT      NOT NULL,
  role                 VARCHAR(15) NOT NULL DEFAULT 'MEMBER',
  estado               VARCHAR(15) NOT NULL DEFAULT 'ACTIVO',
  joined_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
  ended_at             TIMESTAMPTZ NULL,
  invited_by           BIGINT      NULL,
  id_persona           BIGINT      NULL,
  id_profile           BIGINT      NULL,
  created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at           TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT pk_tenant_users
    PRIMARY KEY (id_tenant, id_user),
  CONSTRAINT fk_tenant_users_tenant
    FOREIGN KEY (id_tenant)
    REFERENCES public.tenants (id_tenant),
  CONSTRAINT fk_tenant_users_user
    FOREIGN KEY (id_user)
    REFERENCES public.auth_users (id_user),
  CONSTRAINT fk_tenant_users_invited_by
    FOREIGN KEY (invited_by)
    REFERENCES public.auth_users (id_user),
  -- Impide asignar un perfil perteneciente a otro tenant.
  CONSTRAINT fk_tenant_users_profile
    FOREIGN KEY (id_tenant, id_profile)
    REFERENCES public.tenant_profiles (id_tenant, id_profile),
  CONSTRAINT ck_tenant_users_role
    CHECK (role IN ('OWNER', 'ADMIN', 'MEMBER')),
  CONSTRAINT ck_tenant_users_estado
    CHECK (estado IN ('ACTIVO', 'INACTIVO')),
  CONSTRAINT ck_tenant_users_dates
    CHECK (
      (estado = 'ACTIVO' AND ended_at IS NULL)
      OR
      (estado = 'INACTIVO' AND ended_at IS NOT NULL AND ended_at >= joined_at)
    )
);

CREATE INDEX ix_tenant_users_user_estado
  ON public.tenant_users (id_user, estado);

CREATE INDEX ix_tenant_users_tenant_role_estado
  ON public.tenant_users (id_tenant, role, estado);

-- Garantiza como máximo un OWNER activo por tenant.
CREATE UNIQUE INDEX ux_tenant_users_one_active_owner
  ON public.tenant_users (id_tenant)
  WHERE role = 'OWNER'
    AND estado = 'ACTIVO';

CREATE TRIGGER trg_tenant_users_updated_at
BEFORE UPDATE ON public.tenant_users
FOR EACH ROW
EXECUTE FUNCTION public.set_updated_at();


-- =============================================================================
-- 8. INVITACIONES
-- =============================================================================
--
-- Una invitación puede enviarse aunque el destinatario todavía no tenga cuenta.
-- tenant_users se crea o reactiva únicamente al aceptar la invitación.

CREATE TABLE public.tenant_invitations (
  id_invitation        BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  id_tenant            BIGINT       NOT NULL,
  email                CITEXT       NOT NULL,
  role                 VARCHAR(15)  NOT NULL DEFAULT 'MEMBER',
  id_profile           BIGINT       NULL,
  token_hash           VARCHAR(255) NOT NULL,
  status               VARCHAR(15)  NOT NULL DEFAULT 'PENDING',
  expires_at           TIMESTAMPTZ  NOT NULL,
  accepted_at          TIMESTAMPTZ  NULL,
  rejected_at          TIMESTAMPTZ  NULL,
  revoked_at           TIMESTAMPTZ  NULL,
  invited_by           BIGINT       NOT NULL,
  message              VARCHAR(500) NULL,
  created_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),

  CONSTRAINT pk_tenant_invitations PRIMARY KEY (id_invitation),
  CONSTRAINT fk_tenant_invitations_tenant
    FOREIGN KEY (id_tenant)
    REFERENCES public.tenants (id_tenant),
  CONSTRAINT fk_tenant_invitations_invited_by
    FOREIGN KEY (invited_by)
    REFERENCES public.auth_users (id_user),
  CONSTRAINT fk_tenant_invitations_profile
    FOREIGN KEY (id_tenant, id_profile)
    REFERENCES public.tenant_profiles (id_tenant, id_profile),
  CONSTRAINT ux_tenant_invitations_token_hash UNIQUE (token_hash),
  CONSTRAINT ck_tenant_invitations_role
    CHECK (role IN ('ADMIN', 'MEMBER')),
  CONSTRAINT ck_tenant_invitations_status
    CHECK (
      status IN ('PENDING', 'ACCEPTED', 'REJECTED', 'REVOKED', 'EXPIRED')
    ),
  CONSTRAINT ck_tenant_invitations_expiration
    CHECK (expires_at > created_at),
  CONSTRAINT ck_tenant_invitations_status_dates
    CHECK (
      (status = 'PENDING'
        AND accepted_at IS NULL
        AND rejected_at IS NULL
        AND revoked_at IS NULL)
      OR
      (status = 'ACCEPTED'
        AND accepted_at IS NOT NULL
        AND rejected_at IS NULL
        AND revoked_at IS NULL)
      OR
      (status = 'REJECTED'
        AND accepted_at IS NULL
        AND rejected_at IS NOT NULL
        AND revoked_at IS NULL)
      OR
      (status = 'REVOKED'
        AND accepted_at IS NULL
        AND rejected_at IS NULL
        AND revoked_at IS NOT NULL)
      OR
      (status = 'EXPIRED'
        AND accepted_at IS NULL
        AND rejected_at IS NULL
        AND revoked_at IS NULL)
    )
);

CREATE INDEX ix_tenant_invitations_tenant_status
  ON public.tenant_invitations (id_tenant, status);

CREATE INDEX ix_tenant_invitations_email_status
  ON public.tenant_invitations (email, status);

CREATE INDEX ix_tenant_invitations_expires
  ON public.tenant_invitations (expires_at)
  WHERE status = 'PENDING';

-- Solo puede existir una invitación pendiente por correo dentro del mismo tenant.
CREATE UNIQUE INDEX ux_tenant_invitations_pending_email
  ON public.tenant_invitations (id_tenant, email)
  WHERE status = 'PENDING';

CREATE TRIGGER trg_tenant_invitations_updated_at
BEFORE UPDATE ON public.tenant_invitations
FOR EACH ROW
EXECUTE FUNCTION public.set_updated_at();







