-- -----------------------------------------------------------------------------
-- 12.3. ACEPTAR INVITACIÓN
-- -----------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.accept_tenant_invitation(
  p_token TEXT
)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_user_id       BIGINT;
  v_user_email    CITEXT;
  v_token_hash    TEXT;
  v_invitation    public.tenant_invitations%ROWTYPE;
BEGIN
  v_user_id := public.app_current_user_id();

  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Usuario no autenticado';
  END IF;

  SELECT au.email
  INTO v_user_email
  FROM public.auth_users au
  WHERE au.id_user = v_user_id
    AND au.estado = 'ACTIVO'
    AND au.email_verified = TRUE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'El usuario debe estar activo y tener el correo verificado';
  END IF;

  IF NULLIF(btrim(p_token), '') IS NULL THEN
    RAISE EXCEPTION 'El token es obligatorio';
  END IF;

  v_token_hash := encode(digest(p_token, 'sha256'), 'hex');

  SELECT ti.*
  INTO v_invitation
  FROM public.tenant_invitations ti
  WHERE ti.token_hash = v_token_hash
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Invitación no encontrada';
  END IF;

  IF v_invitation.status <> 'PENDING' THEN
    RAISE EXCEPTION 'La invitación ya no está disponible';
  END IF;

  IF v_invitation.expires_at <= now() THEN
    UPDATE public.tenant_invitations
    SET status = 'EXPIRED'
    WHERE id_invitation = v_invitation.id_invitation;

    RAISE EXCEPTION 'La invitación ha expirado';
  END IF;

  IF v_invitation.email <> v_user_email THEN
    RAISE EXCEPTION 'La invitación corresponde a otro correo electrónico';
  END IF;

  INSERT INTO public.tenant_users (
    id_tenant,
    id_user,
    role,
    estado,
    joined_at,
    ended_at,
    invited_by,
    id_profile
  )
  VALUES (
    v_invitation.id_tenant,
    v_user_id,
    v_invitation.role,
    'ACTIVO',
    now(),
    NULL,
    v_invitation.invited_by,
    v_invitation.id_profile
  )
  ON CONFLICT (id_tenant, id_user)
  DO UPDATE
  SET role = EXCLUDED.role,
      estado = 'ACTIVO',
      joined_at = now(),
      ended_at = NULL,
      invited_by = EXCLUDED.invited_by,
      id_profile = EXCLUDED.id_profile;

  UPDATE public.tenant_invitations
  SET status = 'ACCEPTED',
      accepted_at = now()
  WHERE id_invitation = v_invitation.id_invitation;

  RETURN v_invitation.id_tenant;
END;
$$;

