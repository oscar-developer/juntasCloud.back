-- =============================================================================
-- 5. TENANTS / JUNTAS DIRECTIVAS
-- =============================================================================
--
-- El propietario no se almacena en esta tabla. La fuente de verdad del OWNER
-- es tenant_users, porque un usuario puede tener diferentes roles en distintos
-- tenants.
--
-- nombre, tipo_documento y numero_documento son datos descriptivos y pueden
-- repetirse entre tenants. id_tenant es el identificador único del workspace.

CREATE TABLE public.tenants (
  id_tenant            BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  nombre               VARCHAR(150) NOT NULL,
  tipo_documento       VARCHAR(15)  NULL,
  numero_documento     VARCHAR(20)  NULL,
  
  -- Indica el propósito del espacio de trabajo.
  tenant_type          VARCHAR(15) NOT NULL DEFAULT 'PRACTICE',

  estado               VARCHAR(15)  NOT NULL DEFAULT 'ACTIVO',
  observaciones        VARCHAR(300) NULL,
  deleted_at           TIMESTAMPTZ NULL,
  created_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
  updated_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),

  CONSTRAINT pk_tenants PRIMARY KEY (id_tenant),
  CONSTRAINT ck_tenants_nombre
    CHECK (btrim(nombre) <> ''),
  CONSTRAINT ck_tenants_estado
    CHECK (estado IN ('ACTIVO', 'INACTIVO', 'SUSPENDIDO')),
  CONSTRAINT ck_tenants_tipo_documento
    CHECK (
      tipo_documento IS NULL
      OR tipo_documento IN ('RUC', 'DNI', 'OTRO')
    ),
  CONSTRAINT ck_tenants_documento
    CHECK (
      (tipo_documento IS NULL AND numero_documento IS NULL)
      OR
      (tipo_documento IS NOT NULL AND numero_documento IS NOT NULL)
    ),
  CONSTRAINT ck_tenants_type
    CHECK (
      tenant_type IN ('OFFICIAL', 'PRACTICE', 'DEMO')
    )
);

CREATE INDEX ix_tenants_estado
  ON public.tenants (estado);

-- Índice no único para agilizar búsquedas por documento.
-- Se permiten varios tenants con el mismo nombre, tipo_documento y
-- numero_documento, porque cada espacio de trabajo se identifica por id_tenant.
CREATE INDEX ix_tenants_documento
  ON public.tenants (tipo_documento, numero_documento)
  WHERE tipo_documento IS NOT NULL
    AND numero_documento IS NOT NULL;

CREATE TRIGGER trg_tenants_updated_at
BEFORE UPDATE ON public.tenants
FOR EACH ROW
EXECUTE FUNCTION public.set_updated_at();


