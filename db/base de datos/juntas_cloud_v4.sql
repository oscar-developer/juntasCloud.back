    RAISE EXCEPTION 'No pertenece activamente al tenant';
  END IF;

  IF v_role = 'OWNER' THEN
    RAISE EXCEPTION 'El OWNER debe transferir la propiedad antes de abandonar el tenant';
  END IF;

  UPDATE public.tenant_users
  SET estado = 'INACTIVO',
      ended_at = now()
  WHERE id_tenant = p_tenant_id
    AND id_user = v_user_id;
END;
$$;

ALTER FUNCTION public.leave_tenant(BIGINT)
  OWNER TO juntas_rls_definer;

REVOKE ALL ON FUNCTION public.leave_tenant(BIGINT) FROM PUBLIC;


-- -----------------------------------------------------------------------------
-- 12.9. TRANSFERIR PROPIEDAD
-- -----------------------------------------------------------------------------
--
-- La operación es atómica. El OWNER actual pasa a ADMIN y el miembro indicado
-- se convierte en OWNER dentro de la misma transacción.

CREATE OR REPLACE FUNCTION public.transfer_tenant_ownership(
  p_tenant_id          BIGINT,
  p_new_owner_user_id  BIGINT
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_current_owner_id BIGINT;
BEGIN
  v_current_owner_id := public.app_current_user_id();

  IF v_current_owner_id IS NULL THEN
    RAISE EXCEPTION 'Usuario no autenticado';
  END IF;

  -- Serializa cambios de membresía dentro del tenant.
  PERFORM 1
  FROM public.tenant_users tu
  WHERE tu.id_tenant = p_tenant_id
  ORDER BY tu.id_user
  FOR UPDATE;

  IF NOT EXISTS (
    SELECT 1
    FROM public.tenant_users tu
    WHERE tu.id_tenant = p_tenant_id
      AND tu.id_user = v_current_owner_id
      AND tu.role = 'OWNER'
      AND tu.estado = 'ACTIVO'
  ) THEN
    RAISE EXCEPTION 'Solo el OWNER actual puede transferir la propiedad';
  END IF;

  IF p_new_owner_user_id = v_current_owner_id THEN
    RAISE EXCEPTION 'El usuario indicado ya es el OWNER';
  END IF;

  IF NOT EXISTS (
    SELECT 1
    FROM public.tenant_users tu
    WHERE tu.id_tenant = p_tenant_id
      AND tu.id_user = p_new_owner_user_id
      AND tu.estado = 'ACTIVO'
  ) THEN
    RAISE EXCEPTION 'El nuevo OWNER debe ser miembro activo del tenant';
  END IF;

  UPDATE public.tenant_users
  SET role = 'ADMIN'
  WHERE id_tenant = p_tenant_id
    AND id_user = v_current_owner_id
    AND role = 'OWNER'
    AND estado = 'ACTIVO';

  UPDATE public.tenant_users
  SET role = 'OWNER'
  WHERE id_tenant = p_tenant_id
    AND id_user = p_new_owner_user_id
    AND estado = 'ACTIVO';

  IF NOT FOUND THEN
    RAISE EXCEPTION 'No fue posible establecer el nuevo OWNER';
  END IF;
END;
$$;

ALTER FUNCTION public.transfer_tenant_ownership(BIGINT, BIGINT)
  OWNER TO juntas_rls_definer;

REVOKE ALL ON FUNCTION public.transfer_tenant_ownership(BIGINT, BIGINT)
  FROM PUBLIC;


