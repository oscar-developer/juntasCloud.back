CREATE TABLE public.personas (
  id_persona           BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  id_tenant            BIGINT NOT NULL,

  nro_padron           INTEGER NULL,

  nombres              VARCHAR(100) NOT NULL,
  apellido_paterno     VARCHAR(100) NOT NULL,
  apellido_materno     VARCHAR(100) NOT NULL,
  dni                  VARCHAR(15),
  email                CITEXT NULL,
  telefono             VARCHAR(20),
  direccion            VARCHAR(200),
  referencia_vivienda  VARCHAR(200),

  tipo_participante    VARCHAR(20) NOT NULL DEFAULT 'NO_PADRONADO',
  estado               VARCHAR(20) NOT NULL DEFAULT 'ACTIVO',

  fecha_registro       DATE NOT NULL DEFAULT CURRENT_DATE,
  fecha_baja           DATE NULL,
  observaciones        TEXT,

  created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at           TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT pk_personas PRIMARY KEY (id_persona),

  CONSTRAINT uq_personas_tenant_persona UNIQUE (id_tenant, id_persona),

  CONSTRAINT fk_personas_tenant
    FOREIGN KEY (id_tenant)
    REFERENCES public.tenants (id_tenant),

  CONSTRAINT ck_personas_tipo CHECK (tipo_participante IN ('PADRONADO','NO_PADRONADO','INVITADO')),
  CONSTRAINT ck_personas_estado CHECK (estado IN ('ACTIVO','SUSPENDIDO','RETIRADO','FALLECIDO')),
  CONSTRAINT ck_personas_baja CHECK (fecha_baja IS NULL OR fecha_baja >= fecha_registro),
  CONSTRAINT ck_personas_nro_padron CHECK (nro_padron IS NULL OR nro_padron > 0),
  CONSTRAINT ck_personas_nro_padron_tipo
  CHECK (
    (tipo_participante = 'PADRONADO' AND nro_padron IS NOT NULL)
    OR
    (tipo_participante IN ('NO_PADRONADO', 'INVITADO') AND nro_padron IS NULL)
  )
);

CREATE INDEX inx_personas_tenant ON public.personas (id_tenant);
CREATE INDEX inx_personas_nombre ON public.personas (id_tenant, apellido_paterno, apellido_materno, nombres);

CREATE UNIQUE INDEX ux_personas_nro_padron 
    ON public.personas (id_tenant, nro_padron) 
    WHERE nro_padron IS NOT NULL;

CREATE UNIQUE INDEX ux_personas_dni
    ON public.personas (id_tenant, dni)
    WHERE dni IS NOT NULL;

CREATE UNIQUE INDEX ux_tenant_users_persona
  ON public.tenant_users (id_tenant, id_persona)
  WHERE id_persona IS NOT NULL;

ALTER TABLE public.tenant_users
  ADD CONSTRAINT fk_tenant_users_persona
  FOREIGN KEY (id_tenant, id_persona)
  REFERENCES public.personas (id_tenant, id_persona);

CREATE TRIGGER trg_personas_updated_at
BEFORE UPDATE ON public.personas
FOR EACH ROW
EXECUTE FUNCTION public.set_updated_at();



