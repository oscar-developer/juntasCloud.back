/*
===============================================================================
 JUNTAS CLOUD V4 - MODELO MULTI-TENANT CON RLS
 PostgreSQL
===============================================================================

Objetivo:
  - Cualquier usuario registrado puede crear una o varias juntas (tenants).
  - Distintos tenants pueden tener el mismo nombre, tipo y número de documento.
  - La identidad y el aislamiento de cada junta se basan exclusivamente en id_tenant.
  - El creador queda registrado como OWNER del tenant.
  - El OWNER o un ADMIN puede invitar personas por correo electrónico.
  - La membresía se crea únicamente cuando la invitación es aceptada.
  - Cada tenant tiene como máximo un OWNER activo.
  - El OWNER puede transferir la propiedad a otro miembro activo.
  - Las operaciones sensibles se ejecutan mediante funciones SECURITY DEFINER.

IMPORTANTE:
  1. Este script debe ejecutarse con un usuario administrador de la base de datos.
  2. El backend debe establecer el usuario autenticado al iniciar cada transacción:

       SELECT set_config('app.user_id', '123', true);

     El tercer parámetro TRUE limita el valor a la transacción actual.
  3. No se debe permitir que el cliente establezca libremente app.user_id.
     Esta responsabilidad corresponde exclusivamente al backend.
  4. Al final del script se incluyen GRANT de ejemplo. Reemplazar
     app_authenticated por el rol real utilizado por la aplicación.
===============================================================================
DROP DATABASE IF EXISTS juntascloudv4;
CREATE DATABASE juntascloudv4;
*/

-- =============================================================================
-- 0. EXTENSIONES
-- =============================================================================

CREATE EXTENSION IF NOT EXISTS citext;
CREATE EXTENSION IF NOT EXISTS pgcrypto;


-- =============================================================================
-- 1. ROL INTERNO PARA FUNCIONES RLS
-- =============================================================================
--
-- Las funciones auxiliares consultan tenant_users, tabla que también tiene RLS.
-- Para evitar recursión infinita se utiliza un rol NOLOGIN con BYPASSRLS.
-- Este rol nunca debe utilizarse para conectar la aplicación.
--
-- CREATE ROLE requiere privilegios administrativos en PostgreSQL.

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_roles
    WHERE rolname = 'juntas_rls_definer'
  ) THEN
    CREATE ROLE juntas_rls_definer NOLOGIN BYPASSRLS;
  END IF;
END;
$$;


-- =============================================================================
-- 2. FUNCIONES GENERALES
-- =============================================================================

-- Actualiza automáticamente la columna updated_at.
CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;


-- Recupera el usuario autenticado establecido por el backend.
CREATE OR REPLACE FUNCTION public.app_current_user_id()
RETURNS BIGINT
LANGUAGE sql
STABLE
SET search_path = pg_catalog, public
AS $$
  SELECT NULLIF(current_setting('app.user_id', true), '')::BIGINT;
$$;


