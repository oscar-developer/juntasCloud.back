-- -----------------------------------------------------------------------------
-- 12.6. CAMBIAR ROL O PERFIL DE UN MIEMBRO
-- -----------------------------------------------------------------------------
--
-- OWNER puede modificar ADMIN y MEMBER.
-- ADMIN solo puede modificar miembros MEMBER y no puede asignar OWNER/ADMIN.

CREATE OR REPLACE FUNCTION public.update_tenant_member(
  p_tenant_id          BIGINT,
  p_member_user_id     BIGINT,
  p_new_role           VARCHAR,
  p_new_profile_id     BIGINT DEFAULT NULL
)
RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_actor_id           BIGINT;
  v_actor_role         VARCHAR(15);
  v_current_role       VARCHAR(15);
BEGIN
  v_actor_id := public.app_current_user_id();

  SELECT tu.role
  INTO v_actor_role
  FROM public.tenant_users tu
  WHERE tu.id_tenant = p_tenant_id
    AND tu.id_user = v_actor_id
    AND tu.estado = 'ACTIVO';

  IF NOT FOUND OR v_actor_role NOT IN ('OWNER', 'ADMIN') THEN
    RAISE EXCEPTION 'No tiene permiso para modificar miembros';
  END IF;

  SELECT tu.role
  INTO v_current_role
  FROM public.tenant_users tu
  WHERE tu.id_tenant = p_tenant_id
    AND tu.id_user = p_member_user_id
    AND tu.estado = 'ACTIVO'
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'El miembro activo no existe en el tenant';
  END IF;

  IF p_new_role NOT IN ('ADMIN', 'MEMBER') THEN
    RAISE EXCEPTION 'Use transfer_tenant_ownership para asignar el rol OWNER';
  END IF;

  IF v_current_role = 'OWNER' THEN
    RAISE EXCEPTION 'El OWNER no puede modificarse mediante esta función';
  END IF;

  IF v_actor_role = 'ADMIN' THEN
    IF v_current_role <> 'MEMBER' OR p_new_role <> 'MEMBER' THEN
      RAISE EXCEPTION 'Un ADMIN solo puede administrar miembros con rol MEMBER';
    END IF;
  END IF;

  IF p_new_profile_id IS NOT NULL AND NOT EXISTS (
    SELECT 1
    FROM public.tenant_profiles tp
    WHERE tp.id_tenant = p_tenant_id
      AND tp.id_profile = p_new_profile_id
      AND tp.estado = TRUE
  ) THEN
    RAISE EXCEPTION 'El perfil no existe, está inactivo o pertenece a otro tenant';
  END IF;

  UPDATE public.tenant_users
  SET role = p_new_role,
      id_profile = p_new_profile_id
  WHERE id_tenant = p_tenant_id
    AND id_user = p_member_user_id;
END;
$$;

