-- Verifica si el usuario autenticado es miembro activo del tenant.
CREATE OR REPLACE FUNCTION public.is_active_tenant_member(
  p_tenant_id BIGINT
)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.tenant_users tu
    WHERE tu.id_tenant = p_tenant_id
      AND tu.id_user = public.app_current_user_id()
      AND tu.estado = 'ACTIVO'
  );
$$;

ALTER FUNCTION public.is_active_tenant_member(BIGINT)
  OWNER TO juntas_rls_definer;

REVOKE ALL ON FUNCTION public.is_active_tenant_member(BIGINT) FROM PUBLIC;


-- Verifica si el usuario autenticado tiene uno de los roles administrativos.
CREATE OR REPLACE FUNCTION public.has_tenant_role(
  p_tenant_id BIGINT,
  p_roles TEXT[]
)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.tenant_users tu
    WHERE tu.id_tenant = p_tenant_id
      AND tu.id_user = public.app_current_user_id()
      AND tu.estado = 'ACTIVO'
      AND tu.role = ANY (p_roles)
  );
$$;

ALTER FUNCTION public.has_tenant_role(BIGINT, TEXT[])
  OWNER TO juntas_rls_definer;

REVOKE ALL ON FUNCTION public.has_tenant_role(BIGINT, TEXT[]) FROM PUBLIC;


-- Verifica si un correo corresponde al usuario autenticado y está verificado.
-- Evita que las políticas RLS necesiten acceso directo a auth_users.
CREATE OR REPLACE FUNCTION public.is_current_user_verified_email(
  p_email CITEXT
)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.auth_users au
    WHERE au.id_user = public.app_current_user_id()
      AND au.estado = 'ACTIVO'
      AND au.email_verified = TRUE
      AND au.email = p_email
  );
$$;

ALTER FUNCTION public.is_current_user_verified_email(CITEXT)
  OWNER TO juntas_rls_definer;

REVOKE ALL ON FUNCTION public.is_current_user_verified_email(CITEXT) FROM PUBLIC;


