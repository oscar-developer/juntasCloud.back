  CONSTRAINT fk_tenant_profiles_tenant
    FOREIGN KEY (id_tenant)
    REFERENCES public.tenants (id_tenant),
  CONSTRAINT ux_tenant_profiles_nombre
    UNIQUE (id_tenant, nombre),
  -- Necesaria para las FK compuestas que validan pertenencia al mismo tenant.
