    UNIQUE (id_tenant, id_profile),
  CONSTRAINT ck_tenant_profiles_nombre
    CHECK (btrim(nombre) <> '')
);

CREATE INDEX ix_tenant_profiles_tenant_estado
  ON public.tenant_profiles (id_tenant, estado);

